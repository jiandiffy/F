import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const { default: extension, remoteTools, quote } = await import(pathToFileURL(process.env.F_REMOTE_EXTENSION).href);
const remote = JSON.parse(process.env.F_REMOTE_PROJECT);
const localProxy = process.env.F_LOCAL_PROXY;
const registered = new Map(), hooks = new Map();
const api = { registerTool: t => registered.set(t.name, t), on: (name, fn) => hooks.set(name, fn) };
extension(api);
assert.deepEqual([...registered.keys()].sort(), ['bash','edit','find','grep','ls','read','write']);
const { run } = remoteTools(remote);
const call = async (name, params, signal = new AbortController().signal) => registered.get(name).execute(name, params, signal, undefined, { cwd: localProxy, sessionId: 'isolated-fixture', sessionManager: { getSessionId: () => 'isolated-fixture' } });
const text = result => result.content?.filter(x=>x.type === 'text').map(x=>x.text).join('\n') || '';
const file = "agent folder/中文 ' file.txt";
await call('write', { path: file, content: 'first remote line\n中文 $() `literal`\n' });
assert.match(text(await call('read', { path: file })), /first remote line/);
await call('edit', { path: file, edits: [{ oldText: 'first remote line', newText: 'changed on remote' }] });
assert.match(text(await call('read', { path: file })), /changed on remote/);
assert.match(text(await call('ls', { path: 'agent folder' })), /中文/);
assert.match(text(await call('find', { pattern: '**/*.txt', path: 'agent folder' })), /file.txt/);
assert.match(text(await call('grep', { pattern: 'changed on remote', path: 'agent folder', literal: true })), /changed on remote/);
assert.match(text(await call('bash', { command: "printf 'REMOTE_CWD:%s\\n' \"$PWD\"; printf executed > agent-executed.txt" })), /REMOTE_CWD:/);
assert.equal((await run(`cat < ${quote(path.posix.join(remote.cwd,'agent-executed.txt'))}`)).toString(), 'executed');
assert.match((await readFile(path.posix.join(remote.cwd, file), 'utf8')), /changed on remote/);
await assert.rejects(readFile(path.join(localProxy,file)), /ENOENT/);
console.log('PASS: production remote read/write/edit/ls/find/grep/bash tools and remote cwd, with no local proxy writes');
const pidFile = path.posix.join(remote.cwd,'cancel-test.pid');
const controller = new AbortController();
const long = call('bash', { command: `printf '%s' $$ > ${quote(pidFile)}; sleep 20; printf bad > cancellation-failed.txt` }, controller.signal).catch(e=>e);
for (let i=0;i<100;i++) { try { await run(`test -s ${quote(pidFile)}`); break; } catch {} await new Promise(r=>setTimeout(r,30)); }
const pid = (await run(`cat ${quote(pidFile)}`)).toString();
assert.match(pid,/^\d+$/);
controller.abort();
assert.match(String(await long), /abort/i);
await new Promise(r=>setTimeout(r,800));
await assert.rejects(run(`kill -0 ${pid} 2>/dev/null`));
await assert.rejects(run(`test -e ${quote(path.posix.join(remote.cwd,'cancellation-failed.txt'))}`));
console.log('PASS: Ctrl+C abort cancels the remote process and descendants');
const dead = remoteTools({ ...remote, arguments: remote.arguments.map(v => v === remote.socket ? remote.socket+'.missing' : v) });
await assert.rejects(dead.tools.find(t=>t.name==='read').execute('dead', { path: path.posix.join(remote.cwd,file) }, new AbortController().signal, undefined, { cwd:localProxy }));
console.log('PASS: disconnected remote tools fail instead of reading an existing local file');
const hook = await hooks.get('before_agent_start')({ systemPrompt: 'Current working directory: '+process.cwd() });
assert.match(hook.systemPrompt,/F remote project:/);
assert.match(hook.systemPrompt,/whiteboard_/);
const boardModule = await import(pathToFileURL(process.env.F_WHITEBOARD_EXTENSION).href);
boardModule.default(api);
const {leasesFor}=await import('../../../packages/agent-bus/agent/leases.mjs');
const boardLease=await leasesFor({cwd:localProxy}).claim({owner:'isolated-fixture',rectangle:{x:0,y:0,width:2000,height:2000}});
await call('whiteboard_create', { lease_id:boardLease.id,mode:'replace', layout:'vertical', nodes:[{id:'remote',label:'Remote project'}], edges:[] });
const scene = JSON.parse(await readFile(path.join(process.env.F_BOARD_DIR,'scene.json'),'utf8'));
assert.ok(scene.elements.length > 0);
console.log('PASS: remote agent whiteboard tools use the centralized project board');

const originalDisabled = process.env.F_DISABLED_PLUGINS;
process.env.F_DISABLED_PLUGINS = 'whiteboard';
const disabledTools = new Map();
boardModule.default({ registerTool: tool => disabledTools.set(tool.name,tool) });
assert.equal(disabledTools.size,0);
if (originalDisabled === undefined) delete process.env.F_DISABLED_PLUGINS; else process.env.F_DISABLED_PLUGINS=originalDisabled;
console.log('PASS: disabled whiteboard plugin removes its Agent tools');


// The same DSH skill provider reads remote roots through the authenticated filesystem seam.
const harnessRoot = path.resolve(import.meta.dirname, '../../../runtime/harness');
const { Context, SkillRegistry, filesystemSkills } = await import(pathToFileURL(path.join(harnessRoot,'dist/upstream.mjs')).href);
const { remoteSkillFileSystem } = await import(pathToFileURL(path.join(harnessRoot,'src/adapters/remote-skills.mjs')).href);
const skillContext = new Context();
skillContext.provide('fs', remoteSkillFileSystem(remote, run));
await skillContext.plugin(SkillRegistry);
await skillContext.plugin(filesystemSkills, { watch:false, dshHome:path.posix.join(remote.cwd,'test-user-dsh'), agentsHome:path.posix.join(remote.cwd,'test-user-agents') });
await run(`mkdir -p ${quote(path.posix.join(remote.cwd,'.git'))}`);
const skillFile=path.posix.join(remote.cwd,'.dsh/skills/remote-probe.md');
await call('write',{path:skillFile,content:'---\nname: remote-probe\ndescription: remote skill\n---\nREMOTE_SKILL_FIRST'});
const firstSkill=await skillContext.skills.get('remote-probe',{cwd:remote.cwd});
assert.equal(firstSkill.source,'project-dsh');assert.equal(firstSkill.content,'REMOTE_SKILL_FIRST');
await call('write',{path:skillFile,content:'---\nname: remote-probe\ndescription: remote skill\n---\nREMOTE_SKILL_UPDATED'});
assert.equal((await skillContext.skills.get('remote-probe',{cwd:remote.cwd})).content,'REMOTE_SKILL_UPDATED');
const broken=remoteSkillFileSystem(remote,dead.run);
await assert.rejects(broken.readText({displayPath:skillFile}));
await skillContext.fiber.dispose();
console.log('PASS: official DSH remote skill discovery, fresh bodies and no local fallback after disconnect');
